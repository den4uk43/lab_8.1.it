#define _CRT_SECURE_NO_WARNINGS 
#include <iostream> 
#include <cstring> // Необхідно для функцій strlen, strcat, strcpy

using namespace std;

// 1. Функція для підрахунку кількості груп з трьох послідовних зірочок "***"
int Count(char* str)
{
    // Якщо довжина рядка менша за 3, в ньому фізично не може бути групи з 3 зірочок
    if (strlen(str) < 3)
        return 0;

    int k = 0; // Лічильник знайдених груп

    // Проходимо циклом по символах рядка. Починаємо з індекса 1, 
    // щоб перевіряти поточний символ разом із сусідніми зліва та справа.
    for (int i = 1; str[i + 1] != 0; i++)
    {
        // Якщо поточний символ і його сусіди зліва та справа є зірочками '*'
        if (str[i - 1] == '*' && str[i] == '*' && str[i + 1] == '*')
            k++; // Збільшуємо лічильник знахідок
    }
    return k;
}

// 2. Функція для заміни кожної трійки зірочок "***" на пару знаків оклику "!!"
char* Change(char* str)
{
    size_t len = strlen(str);

    // Якщо рядок занадто короткий, повертаємо його без змін
    if (len < 3)
        return str;

    // Виділяємо динамічну пам'ять під новий рядок (із запасом)
    char* tmp = new char[len + 1];
    char* t = tmp; // Вказівник для запису в новий рядок
    tmp[0] = '\0'; // Робимо його порожнім рядком на старті

    size_t i = 0;

    // Перебираємо рядок за допомогою циклу while
    while (i < len && str[i + 2] != 0)
    {
        // Якщо знайшли трійку зірочок "***" підряд
        if (str[i] == '*' && str[i + 1] == '*' && str[i + 2] == '*')
        {
            strcat(t, "!!"); // Додаємо замість них "!!" у новий рядок
            t += 2;          // Зсуваємо вказівник нового рядка на 2 символи вперед
            i += 3;          // Пропускаємо ці 3 зірочки у вхідному рядку
        }
        else
        {
            // Якщо зірочок немає, просто копіюємо поточний символ з str у tmp
            *t++ = str[i++];
            *t = '\0';       // Завжди закриваємо рядок нуль-символом
        }
    }

    // Дописуємо залишок символів рядка, які не увійшли в цикл перевірки
    while (i < len)
    {
        *t++ = str[i++];
    }
    *t = '\0'; // Фінальний нуль-символ в кінці

    // Копіюємо сформований новий рядок назад у початковий масив `str`
    strcpy(str, tmp);

    return tmp; // Повертаємо вказівник на змінений рядок
}

int main()
{
    char str[101];

    cout << "Enter string:" << endl;
    cin.getline(str, 100); // Зчитуємо рядок з клавіатури (з пробілами)

    // Викликаємо функцію Count і виводимо результат
    int count = Count(str);
    cout << "String contained " << count << " groups of '***'" << endl;

    if (count > 0)
        cout << "Group '***' was found in the string." << endl;
    else
        cout << "Group '***' was NOT found in the string." << endl;

    // Викликаємо функцію Change для модифікації рядка
    char* dest = Change(str);

    // Виводимо модифіковані рядки (через параметр і через результат функції)
    cout << "Modified string (param) : " << str << endl;
    cout << "Modified string (result): " << dest << endl;

    return 0;
}